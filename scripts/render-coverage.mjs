#!/usr/bin/env node
// Render COVERAGE.md from a get_public_coverage() payload.
//
// Reads the JSON payload on stdin and writes markdown to stdout. Pure: no
// network, no filesystem, no clock. That last one is deliberate — see below.
//
// NO RENDER TIMESTAMP IN THE OUTPUT. The workflow commits only when the file
// changes, and a "generated at <now>" line would change on every single run,
// making every run a commit and the commit history useless as a record of
// whether coverage actually moved. Freshness is still visible: every row
// carries the source's own last-success stamp, the header carries
// counts_refreshed_at, and GitHub shows when the file last changed. All
// timestamps come from the payload, never from this process.
//
// Usage:  node scripts/render-coverage.mjs < payload.json > COVERAGE.md

import { pathToFileURL } from "node:url";

const FEDERAL_CODE = "US";

const SOURCE_LABELS = {
  federal_bills: "Federal bills",
  state_bills: "State legislation",
  agency_actions: "Agency actions",
  court_cases: "Court cases",
  enacted_laws: "Enacted laws",
  committees: "Committees",
  hearings: "Hearings",
};

const SOURCE_STATE = {
  operational: "🟢 Operational",
  delayed: "🟡 Delayed",
  unknown: "⚪ Unknown",
};

const JURISDICTION_STATE = {
  live: "🟢 Live",
  stale: "🟡 Stale",
  dormant: "⚪ Dormant",
};

/** "2026-08-05T12:07:47.636896+00:00" -> "2026-08-05 12:07 UTC" */
function utc(iso) {
  if (!iso) return "never";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "unknown";
  const p = (n) => String(n).padStart(2, "0");
  return (
    `${d.getUTCFullYear()}-${p(d.getUTCMonth() + 1)}-${p(d.getUTCDate())} ` +
    `${p(d.getUTCHours())}:${p(d.getUTCMinutes())} UTC`
  );
}

const num = (n) => Number(n ?? 0).toLocaleString("en-US");

/** Pipes would break the table; nothing else in this data needs escaping. */
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");

export function renderCoverage(payload) {
  const sources = Array.isArray(payload?.sources) ? payload.sources : [];
  const all = Array.isArray(payload?.jurisdictions) ? payload.jurisdictions : [];

  const federal = all.find((j) => j.code === FEDERAL_CODE) ?? null;
  const states = all
    .filter((j) => j.code !== FEDERAL_CODE)
    .sort((a, b) => String(a.name ?? a.code).localeCompare(String(b.name ?? b.code)));

  const tally = { live: 0, stale: 0, dormant: 0 };
  for (const j of states) {
    if (j.state in tally) tally[j.state] += 1;
  }

  const totalBills = all.reduce((sum, j) => sum + Number(j.bill_count ?? 0), 0);

  const out = [];

  out.push("# RegLens coverage");
  out.push("");
  out.push(
    "<!-- Generated by .github/workflows/coverage-board.yml from " +
      "get_public_coverage(). Do not edit by hand. -->",
  );
  out.push("");
  out.push(
    "Every jurisdiction [RegLens](https://www.reglens.info) carries, how much of " +
      "it there is, and when it last updated. Regenerated every 6 hours; the " +
      "commit history of this file is the record of when coverage actually moved.",
  );
  out.push("");
  out.push(
    `**${num(totalBills)} bills** across **${all.length} jurisdictions** — ` +
      `federal plus ${states.length} state-level jurisdictions.`,
  );
  out.push("");
  out.push(
    `State-level: **${tally.live} live · ${tally.stale} stale · ` +
      `${tally.dormant} dormant**. Bill counts as of ${utc(payload?.counts_refreshed_at)}.`,
  );
  out.push("");

  out.push("## Data sources");
  out.push("");
  out.push("| Source | Last success | Status |");
  out.push("| --- | --- | --- |");
  for (const s of sources) {
    out.push(
      `| ${cell(SOURCE_LABELS[s.key] ?? s.key)} | ${utc(s.last_success_at)} | ` +
        `${SOURCE_STATE[s.state] ?? SOURCE_STATE.unknown} |`,
    );
  }
  out.push("");

  out.push("## Jurisdictions");
  out.push("");
  out.push(
    "**Live** — the active sync lane succeeded in the last 36 hours. " +
      "**Stale** — a lane exists but has not succeeded recently. " +
      "**Dormant** — bills are held but nothing is currently maintaining them. " +
      "Dormant lanes are named rather than hidden.",
  );
  out.push("");
  out.push(
    "Freshness is when a source last *reported*, not when a legislature last " +
      "*acted* — a quiet chamber and a stalled feed are different things.",
  );
  out.push("");
  out.push("| Jurisdiction | Bills | Last success | Status |");
  out.push("| --- | ---: | --- | --- |");
  if (federal) {
    out.push(
      `| **Federal — U.S. Congress** | ${num(federal.bill_count)} | ` +
        `${utc(federal.last_success_at)} | ` +
        `${JURISDICTION_STATE[federal.state] ?? JURISDICTION_STATE.dormant} |`,
    );
  }
  for (const j of states) {
    out.push(
      `| ${cell(j.name ?? j.code)} | ${num(j.bill_count)} | ` +
        `${utc(j.last_success_at)} | ` +
        `${JURISDICTION_STATE[j.state] ?? JURISDICTION_STATE.dormant} |`,
    );
  }
  out.push("");

  out.push("---");
  out.push("");
  out.push(
    "Source data: [Congress.gov](https://www.congress.gov), " +
      "[LegiScan](https://legiscan.com), " +
      "[Federal Register](https://www.federalregister.gov), " +
      "[CourtListener](https://www.courtlistener.com). " +
      "See [system status](https://www.reglens.info/status) for the live view.",
  );
  out.push("");

  return out.join("\n");
}

/** Read all of stdin. Returns "" when nothing is piped. */
async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString("utf8");
}

// Only run when invoked directly, so the renderer stays importable for tests.
// pathToFileURL, not string concatenation: on Windows argv[1] is "C:\..." and
// a hand-built "file://C:/..." has two slashes where import.meta.url has three,
// so the guard silently never fires and the script writes nothing.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const raw = await readStdin();
  if (!raw.trim()) {
    console.error("render-coverage: no payload on stdin");
    process.exit(1);
  }

  let payload;
  try {
    payload = JSON.parse(raw);
  } catch (e) {
    console.error(`render-coverage: payload is not valid JSON: ${e.message}`);
    process.exit(1);
  }

  // A payload with no jurisdictions means the RPC answered but told us nothing.
  // Writing that out would replace a good board with an empty one and commit
  // the result, so refuse instead — fail loud, leave the last good file alone.
  if (!Array.isArray(payload?.jurisdictions) || payload.jurisdictions.length === 0) {
    console.error("render-coverage: payload carries no jurisdictions — refusing to render");
    process.exit(1);
  }

  process.stdout.write(renderCoverage(payload));
}
